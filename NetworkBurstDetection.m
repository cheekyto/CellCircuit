function NetworkBurstDetection=NetworkBurstDetection(spikeTrain, BurstDetected, range, option_method, opt_distance, option_plot)

% function to detect network bursts in a spike train data, using the method specified 
% (spikeTimestamp and BurstDetected should be restricted to the same temporal window)

% When trying to identify small network bursts within an active recording, the parameters that have the most impact are:
% THRESHOLD in NetworkBurstDetection
% ACTIVITY_THRESHOLD_FINAL in findChannel_in_Peak

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%%%%%%%%%%%%%%%%%%%%%%%%%   INPUTS   %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%   structure array spikeTimestamp (its length is the number of recording channels), with the following fields
% 	.recLength:	length of the recording, in seconds.
% 	.nUnits:	total number of identified units in the channel
% 	.timeStamp:	time stamp for all units (nUnits) in the channel, in msec

%   BurstDetected:      structure generated by the function "BurstDetection"
%   range:              range of the recording (range(1)=start; range(2)=end), in sec
% 	option_method:	    option input to specified the algorithm to be used for burst detection
%               =1      Looking for peaks in the population firing rate, with a FIXED bin size (as option 2, but without the search of the optimal bin size)
%               =2      looking for peaks, combining the regular population firing rate and the normalized population firing; and using a progressive narrowing of the binSize
%               =3      option 2 + burst family clustering
%   option_plot:

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%%%%%%%%%%%%%%%%%%%%%%%%%   OUTPUT   %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

% NetworkBurstDetection.spikesBin(i,1):         total number of spikes in bin i
% NetworkBurstDetection.time(i):                midpoint of the bin i, in sec 
% NetworkBurstDetection.IndivBurst(j).start:    start point of network burst j, in sec
% NetworkBurstDetection.IndivBurst(j).last:     last point of network burst j, in sec
% NetworkBurstDetection.IndivBurst(j).window:   temporal window to extract spike train from network burst j, in sec (revised October 2026: it was documented in ms)
% NetworkBurstDetection.IndivBurst(j).peak:     peak point of network burst j, in sc
% NetworkBurstDetection.IndivBurst(k).peakIdx:  peak point of network burst j
% NetworkBurstDetection.parameter:              structure with information about the network burst detection method
% NetworkBurstDetection.nBurst:                 total number of network bursts 
% NetworkBurstDetection.Channels(i,1):          list of channels that robustly participate of network bursting     
% NetworkBurstDetection.timeStamp{i,j}:         time stamp of the spikes for the burst i coming from channel j (all channels), in msec

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%   PARAMETERS   %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

MIN_CHAN = 6;                                   % minimum number of participating channels/units to classify an organoid as network bursting (default: 6)
MIN_CHAN_BURST = 5;                             % minimum number of channels/units in a single network burst (default: 5)
THRESHOLD_BURST_WITH_UNITS = 0.50;              % minimum proportion of potential network burst with MIN_CHAN_BURST units (default: 0.50)
K_MSEC_SEC = 1/1000;                            % factor to rescale from msec to sec
MIN_CHAN_RATIO = 0.075;                         % minimum number of participating channels/units to classify an organoid as network bursting, as a proportion of the total number of units (default: 0.075)
MIN_CHAN_BURST_RATIO = 0.01;                    % minimum number of channels/units in a single network burst, as a proportion of the total number of units (default: 0.05)

FACTOR_FIRST_ROUND = 0.80;                       % (default: 0.8)

MIN_CHAN_SECONDARY = 0.25;                      % minimum number of participating channels/units to accept the secondary events, in terms of the number of participating units in the primary events (default: 0.25)
MIN_PEAK2_GAP = 1;                              % minimum number of secondary events per gap/window, after a level-1 primary event (default: 1)
GAP_WITH_PEAK = 0.75;                           % minimum proportion of gaps/windows (level-1 primary events) followed by MIN_PEAK2_GAP secondary events, to accept
                                                % the secondary events (default: 0.75) (revised October 2026: from "NetworkBurstPlayers", where it never ran)
apply_parameters('NetworkBurstDetection');                                  % (revised October 2026) values of the parameter set of "run_pipeline", if any (see "pipeline_parameters")

switch option_method

    case 1          % Population firing rate with a FIXED bin size, single burst family
                    % (revised October 2026: same procedure as method 2, but every round uses the bin size BIN, without searching the optimal one;
                    %  before, it called "PopulationActivityDetection" directly, which does not provide the secondary events and the level-1
                    %  information needed by "NetworkBurstPlayers", so it always crashed)
        BIN = 0.3;                              % size of the temporal bin to calculate the population firing rate, in sec (0.2-0.4)
        THRESHOLD = 5.0;                        % in terms of the standard deviation (ventral: 3.0 - 5.0 ; dorsal: 5.0 - 8.0)
        MIN_ROBUST = 4;                         % minimum number of robustly participating clusters (default: 4, as in method 2)
        apply_parameters('NetworkBurstDetection', 'method1');               % (revised October 2026) values of the parameter set of "run_pipeline", if any (see "pipeline_parameters")
        BIN_MIN = BIN;  BIN_MAX = BIN;          % the bin size is fixed: the "search" of the optimal bin size only tests BIN
        BIN_DEFAULT = BIN;                      % (not used: the search cannot fail with a single bin size)
        parameters = struct('method','Population firing rate, fixed bin size','THRESHOLD',THRESHOLD,'BIN',BIN);
        
    case 2          % Normalized Population firing rate, with dynamic bin size, single burst family

        BIN_MIN = 0.01;                         % minimum size of the temporal bin to calculate the population firing rate, in sec (default: 0.01 sec)
        BIN_MAX = 3.0;                          % maximum size of the temporal bin to calculate the population firing rate, in sec (default: 3.0 sec)
        THRESHOLD = 5.0;                        % in terms of the standard deviation (default: 5.0)
        BIN_DEFAULT = 0.20;                     % default size of the temporal bin to calculate the population firing rate, in sec (default: 0.25 sec) 
        MIN_ROBUST = 4;                         % minimum number of robustly participating clusters (default: 4)
        apply_parameters('NetworkBurstDetection', 'method2');               % (revised October 2026) values of the parameter set of "run_pipeline", if any (see "pipeline_parameters")
        parameters = struct('method','Normalized Population firing rate','THRESHOLD',THRESHOLD,'BIN_MIN',BIN_MIN,'BIN_MAX',BIN_MAX);

    case 3         % Normalized Population firing rate, with dynamic bin size, burst family clustering

        BIN_MIN = 0.01;                         % minimum size of the temporal bin to calculate the population firing rate, in sec (default: 0.01 sec)
        BIN_MAX = 3.0;                          % maximum size of the temporal bin to calculate the population firing rate, in sec (default: 3.0 sec)
        THRESHOLD = 6.0;                        % in terms of the standard deviation (default: 5.0; it must be >3.5)
        BIN_DEFAULT = 0.10;                     % default size of the temporal bin to calculate the population firing rate, in sec (default: 0.15 sec) 
        MIN_ROBUST = 5;                         % minimum number of robustly participating clusters (default: 5)
        apply_parameters('NetworkBurstDetection', 'method3');               % (revised October 2026) values of the parameter set of "run_pipeline", if any (see "pipeline_parameters")
        parameters = struct('method','Normalized Population firing rate','THRESHOLD',THRESHOLD,'BIN_MIN',BIN_MIN,'BIN_MAX',BIN_MAX);
end

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% Burst Detection using the method "option_method"

n_clusters = size(spikeTrain,2);                                            % total number of clusters
option_clustering = 0;
if option_method==3
    option_method=2;
    option_clustering=1;
end
fixed_bin = false;                                                          % (revised October 2026) method 1 = method 2 with the bin size fixed to BIN
if option_method==1
    option_method=2;
    fixed_bin = true;
end

t0=tic;
shuffleCache('reset');                                                      % (revised October 2026) the shuffles of each cluster are generated once per run (see "shuffleCache")
fprintf("\n \n Starting the Network Burst detection (step 0 out of 4)... \n");
switch option_method

%    (revised October 2026) method 1 now runs the code of method 2 below, with "fixed_bin = true" (the previous code of method 1 was removed)

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    case 2          % Normalized Population firing rate (each neuron's data is normalized to the its total number of spikes), with dynamic bin size

        flag1 = 0;
        units = ones(n_clusters,1);                                         % ALL clusters
        % Preliminary screen using all channels (identify peaks and participating neurons); look for population peaks
        PopulationActivityDetected_beta = DynamicPopActDetect(units, spikeTrain, BurstDetected, range, BIN_MIN, BIN_MAX, nan, THRESHOLD*FACTOR_FIRST_ROUND, opt_distance, 0, 1, 0); 
        if isnan(PopulationActivityDetected_beta.bin)                       % if the optimal bin size could not been found
            PopulationActivityDetected_beta = PopActivityPeak_Integration(units,spikeTrain, BurstDetected, range, BIN_DEFAULT, THRESHOLD*FACTOR_FIRST_ROUND, 1, opt_distance, 0, 1, option_plot);
                                                                            % (revised October 2026) plots only if option_plot (before, always: opt_plot = 1)
            PopulationActivityDetected_beta.bin = BIN_DEFAULT;              % use the default bin size
            flag1 = 1;                                                      % flag1 == 1, could not find optimal bin size; flag1 == 0, optimal bin size was successfully identified    
            fprintf("\n After the first search round,  the optimal bin size was NOT identified (step 1 out of 4, %f min) \n", toc(t0)/60);        
        end
        t1=tic;
        flag_delta = 0;                                                     % (revised October 2026) same as flag1, for the non-normalized signal
        PopulationActivityDetected_delta = DynamicPopActDetect(units, spikeTrain, BurstDetected, range, BIN_MIN, BIN_MAX, nan, THRESHOLD*FACTOR_FIRST_ROUND, opt_distance, 0, 0, 0); 
        if isnan(PopulationActivityDetected_delta.bin)                       % if the optimal bin size could not been found
            PopulationActivityDetected_delta = PopActivityPeak_Integration(units,spikeTrain, BurstDetected, range, BIN_DEFAULT, THRESHOLD*FACTOR_FIRST_ROUND, 0, opt_distance, 0, 1, 0);
            PopulationActivityDetected_delta.bin = BIN_DEFAULT;              % use the default bin size
            flag_delta = 1;                                                 % the optimal bin size was NOT identified with the non-normalized signal
        end
        if PopulationActivityDetected_delta.nBurst > PopulationActivityDetected_beta.nBurst
            PopulationActivityDetected_beta = PopulationActivityDetected_delta;
            flag1 = flag_delta;                                             % (revised October 2026) flag1 describes the result that is kept: =1 if it used the default bin size
                                                                            % (before, it still described the normalized signal after being replaced by the non-normalized one)
            fprintf("\n The non-normalized signal deliverd more primary events than the normalized signal (step 2 out of 4, %f min) \n", toc(t1)/60);
        else
            fprintf("\n The normalized signal delivered more primary events than the non-normalized signal (step 2 out of 4, %f min) \n", toc(t1)/60);
        end
        t2 = tic;
        NetworkBurstPlayer_beta = NetworkBurstPlayers(spikeTrain, range, PopulationActivityDetected_beta, BurstDetected, 1, PopulationActivityDetected_beta.bin , THRESHOLD*FACTOR_FIRST_ROUND, opt_distance, 0);  % robust vs weak

        % Refined/final analysis; look for population peaks using only the robustly participating clusters
        % NOTE (October 2026): the refined round ("alpha"), the final round and the final re-detection with the participating units (inside 
        % "NetworkBurstPlayers", option 2) always use the NORMALIZED population signal (opt_norm = 1), whichever signal (normalized "beta" or 
        % non-normalized "delta") was kept in the preliminary round above. This is intended. To use the non-normalized signal instead, change 
        % opt_norm from 1 to 0 in: "DynamicPopActDetect" (11th input) and "PopActivityPeak_Integration" (7th input) below, and in 
        % "NetworkBurstPlayers" (the call "PopActivityPeak_Integration(participation, ...)" of option 2)
        flag2 = 0;
        units = zeros(n_clusters,1);
        participants = union(NetworkBurstPlayer_beta.Channels, NetworkBurstPlayer_beta.Secondary.Channels);
        units(participants,1)=1;                                            % all clusters robustly participating in network bursting  
        if sum(units)<MIN_ROBUST                                            % if the number of robustly participating clusters is too low                                               
            units = ones(n_clusters,1);                                     % ALL clusters
            PopulationActivityDetected = PopulationActivityDetected_beta;   % use the analysis with all units 
            bin_final = PopulationActivityDetected.bin;
            flag2 = 2;                                                      % flag2 == 2, the number of robustly participating units is too low 
            fprintf("\n The number of robustly participating units is too low (step 3 out of 4, %f min) \n", toc(t2)/60);
            t3=tic;
        else                                                                % if the number of robustly participating clusters is enough
            bin_center = PopulationActivityDetected_beta.bin;               % refined search of the bin size, around the one found in the first round
            if fixed_bin                                                    % (revised October 2026) method 1: no refined search, the bin size is fixed (BIN)
                bin_center = nan;
            end
            PopulationActivityDetected_alpha = DynamicPopActDetect(units, spikeTrain, BurstDetected, range, BIN_MIN, BIN_MAX, bin_center, THRESHOLD, opt_distance, 0, 1, 0); 

            if isnan(PopulationActivityDetected_alpha.bin)                  % if the optimal bin size could not been found
                PopulationActivityDetected_alpha = PopActivityPeak_Integration(units,spikeTrain, BurstDetected, range, BIN_DEFAULT, THRESHOLD, 1, opt_distance, 0, 1, 0);
                PopulationActivityDetected_alpha.bin = BIN_DEFAULT;         % use the default bin size
                flag2 = 1;                                                  % flag2 == 1, the optimal bin size could not been identified (when using only the robustly participating clusters)
                bin_final = (PopulationActivityDetected_beta.bin + PopulationActivityDetected_alpha.bin)/2;     % compromised solution 
            else
                if flag1                                                    % if the preliminary result that was kept used the default bin size (optimal bin size NOT identified)
%                    bin_final = (PopulationActivityDetected_beta.bin + PopulationActivityDetected_alpha.bin*4)/5;   % weighted average                    
                    bin_final = PopulationActivityDetected_alpha.bin;       % (revised October 2026: ";" added, it printed the value)
                else                                                            % if the optimal bin size was identified
                    bin_final = (PopulationActivityDetected_beta.bin + PopulationActivityDetected_alpha.bin*2)/3;   % weighted average
                end
            end
            fprintf("\n About to run the final round of Peak detection (step 3 out of 4, %f min) ... \n ", toc(t2)/60);
            t3=tic;
            PopulationActivityDetected = DynamicPopActDetect(units, spikeTrain, BurstDetected, range, bin_final, bin_final, nan, THRESHOLD, opt_distance, 1, 1, option_plot); % final round of peak detection, using "bin_final"          
                                                                            % (revised October 2026) plots only if option_plot (before, always: opt_plot = 1, which also ran
                                                                            %  up to 3 extra detections, only to plot them, in "DynamicPopActDetect")
        end

        fprintf("\n About to run statistical assessment (step 4 out of 4, %f min) \n", toc(t3)/60);
        fprintf("   We are starting with %g primary events (%g level1) and %g secondary events \n",PopulationActivityDetected.nBurst, PopulationActivityDetected.nBurst_level1, PopulationActivityDetected.Secondary.nBurst);
        t4=tic;
        % Statistical assessment and final "PopActivityPeak_Integration" with the final list of participating units
        NetworkBurstPlayer = NetworkBurstPlayers(spikeTrain, range, PopulationActivityDetected, BurstDetected, 2, bin_final, THRESHOLD, opt_distance, option_plot); % statistical assessment 
        fprintf("   After the statistical assessment, we have %g primary events (%g level1) and %g secondary events \n",NetworkBurstPlayer.nBurst, NetworkBurstPlayer.nBurst_level1,NetworkBurstPlayer.Secondary.nBurst);

        % Final Quality Control on primary events
        low_units = nan;
        if NetworkBurstPlayer.nBurst > 0                    
            n_participating = numel(NetworkBurstPlayer.Channels(:,1));
            min_units = max(MIN_CHAN, MIN_CHAN_RATIO*n_clusters);
            if n_participating < min_units                                   % the number of participating units in primary events is too low
                NetworkBurstPlayer.nBurst = nan;                            
            else                                                            % enough number of participating units in primary events
                low_units = 0;
                min_units_burst = max(MIN_CHAN_BURST, MIN_CHAN_BURST_RATIO *n_clusters);
                for k=1:NetworkBurstPlayer.nBurst                           % across all primary events  
                    contador = 0;
                    for i=1:n_participating                                 % across all participating units
                        ch = NetworkBurstPlayer.Channels(i,1);
                        if numel(NetworkBurstPlayer.timeStamp{k,ch})>0  
                            contador = contador + 1;                        % total number of clusters with activity during event k
                        end
                    end
                    if contador < min_units_burst
                        low_units = low_units + 1;                          % total number of events with low number of active clusters
                    end
                    clear contador
                end
                if low_units/NetworkBurstPlayer.nBurst > (1-THRESHOLD_BURST_WITH_UNITS)
                    low_units = low_units/NetworkBurstPlayer.nBurst;        % (revised October 2026) proportion calculated BEFORE setting nBurst = NaN 
                    NetworkBurstPlayer.nBurst = nan;                        % (the two lines were in the opposite order, so "lowUnits" was always NaN)
                end
            end
        end
        
        % Final Quality Control on secondary events
        if NetworkBurstPlayer.nBurst > 0 && NetworkBurstPlayer.Secondary.nBurst > 0                    
            n_participating2 = numel(NetworkBurstPlayer.Secondary.Channels(:,1));
            unit_min = max(MIN_CHAN, n_participating*MIN_CHAN_SECONDARY);   % minimum number of participating units for secondary events
            % it will check the secondary events, one by one     
            cant_event = NetworkBurstPlayer.Secondary.nBurst;
            cant_event0 = cant_event;
            % (revised October 2026) the "parent" of a secondary event is the index of its gap, and the gaps follow the level-1 primary events
            % (option_level = 1); before, "parent" was used as an index of ALL primary events, so the secondary peak was compared with the end
            % of a different (earlier) primary event
            idx_parent = find([NetworkBurstPlayer.IndivBurst.level] == 1);  % primary event that defines each gap (level-1 primary events)
            if numel(idx_parent) ~= numel(NetworkBurstPlayer.Secondary.nBurst_per_gap)  % the gaps were defined by all the primary events (option_level = 0)
                idx_parent = 1:NetworkBurstPlayer.nBurst;
            end
            for k=NetworkBurstPlayer.Secondary.nBurst:-1:1                  % across all secondary events  
                parent = NetworkBurstPlayer.Secondary.IndivBurst(k).parent;
                if NetworkBurstPlayer.IndivBurst(idx_parent(parent)).last < NetworkBurstPlayer.Secondary.IndivBurst(k).peak     % the secondary peak is after the end of its parent (level-1) primary event
                    contador = 0;
                    for i=1:n_participating2                                    % across all participating units
                        ch = NetworkBurstPlayer.Secondary.Channels(i,1);
                        if numel(NetworkBurstPlayer.Secondary.timeStamp{k,ch})>0  
                            contador = contador + 1;                            % total number of clusters with activity during event k
                        end
                    end
                else
                    contador = 0;
                end   
                
                if contador < unit_min                                      % if the number of participating units is too low                 
                    cant_event = cant_event - 1;   
                    parent = NetworkBurstPlayer.Secondary.IndivBurst(k).parent;
                    NetworkBurstPlayer.Secondary.nBurst_per_gap(parent) = NetworkBurstPlayer.Secondary.nBurst_per_gap(parent) - 1;
                    NetworkBurstPlayer.Secondary.IndivBurst(k) = [];        % delete the secondary event k
                    NetworkBurstPlayer.Secondary.timeStamp(k,:) = [];       % (revised October 2026) and its spike times; before, they were kept, so the rows of 
                                                                            % "timeStamp" no longer matched the events (features and clustering read the wrong spikes)
                end                    
                clear contador
            end
            NetworkBurstPlayer.Secondary.nBurst = cant_event;
            fprintf("\n Started with %g secondary peaks, and it kept %g of them \n", cant_event0, cant_event);

            % (revised October 2026) the secondary events are accepted only if enough level-1 primary events are followed by them: at least
            % MIN_PEAK2_GAP secondary events in more than GAP_WITH_PEAK of the gaps/windows. The rule was in "NetworkBurstPlayers" (option 1), where
            % it never ran (FAST_MODE). It is checked after the quality control of each secondary event and BEFORE the level-0 primary events that
            % coincide with a secondary event are removed: if the secondary events are rejected, those primary events are kept as primary events
            n_gap = numel(NetworkBurstPlayer.Secondary.nBurst_per_gap);     % number of gaps/windows (one per level-1 primary event)
            gap_with_peak = sum(NetworkBurstPlayer.Secondary.nBurst_per_gap >= MIN_PEAK2_GAP)/max(n_gap, 1);   % proportion of gaps with secondary events
            if cant_event > 0 && gap_with_peak <= GAP_WITH_PEAK               % not enough gaps with secondary events: they are not secondary events
                fprintf("\n Only %.0f%% of the level-1 primary events are followed by secondary events (minimum: %.0f%%): the %g secondary events are rejected \n", ...
                    100*gap_with_peak, 100*GAP_WITH_PEAK, cant_event);
                cant_event = 0;
                NetworkBurstPlayer.Secondary.nBurst = 0;
                NetworkBurstPlayer.Secondary.nBurst_per_gap(:) = 0;
                NetworkBurstPlayer.Secondary.IndivBurst = NetworkBurstPlayer.Secondary.IndivBurst([]);   % (same state as when every secondary event fails the
                NetworkBurstPlayer.Secondary.timeStamp = NetworkBurstPlayer.Secondary.timeStamp([],:);    %  quality control above)
            elseif cant_event > 0
                fprintf("\n %.0f%% of the level-1 primary events are followed by secondary events (minimum: %.0f%%) \n", 100*gap_with_peak, 100*GAP_WITH_PEAK);
            end

            % (revised October 2026) the secondary search (after each level-1 primary event) also detects most of the level-0 primary events that
            % follow it: the same population event was counted twice (as primary and as secondary). A population event right after a level-1 
            % primary event is a secondary event: the level-0 primary events that contain the peak of a secondary event (which passed all the 
            % quality controls above) are removed from the primary events
            if cant_event > 0
                secondary_peak = [NetworkBurstPlayer.Secondary.IndivBurst.peak];   % peak of each secondary event, in sec
                primary_level = [NetworkBurstPlayer.IndivBurst.level];
                primary_start = [NetworkBurstPlayer.IndivBurst.start];
                primary_last = [NetworkBurstPlayer.IndivBurst.last];
                duplicated = false(1, numel(NetworkBurstPlayer.IndivBurst));
                for k = find(primary_level == 0)                            % across all level-0 primary events
                    duplicated(k) = any(secondary_peak >= primary_start(k) & secondary_peak <= primary_last(k));
                end
                if any(duplicated)
                    NetworkBurstPlayer.IndivBurst(duplicated) = [];         % delete the level-0 primary events that are secondary events
                    NetworkBurstPlayer.timeStamp(duplicated,:) = [];        % and their spike times
                    NetworkBurstPlayer.nBurst = NetworkBurstPlayer.nBurst - sum(duplicated);    % (nBurst_level1 does not change)
                end
                fprintf("\n %g level-0 primary events were also secondary events: they are kept only as secondary events \n", sum(duplicated));
            end
        end

        if isnan(NetworkBurstPlayer.nBurst) || NetworkBurstPlayer.nBurst==0
            fprintf("\n\n No Network bursting!!! \n\n")
            clustering = [];
        else
            clustering = clusterNetburst(NetworkBurstPlayer, spikeTrain, BurstDetected, range, flag2, option_clustering);
        end

        % Prepare the output
        NetworkBurstDetection = NetworkBurstPlayer;                         % the final definitive run of "PopulationActivityDetection" was run inside "NetworkBurstPlayers"
        NetworkBurstDetection.parameter = parameters;
        NetworkBurstDetection.lowUnits = low_units;
        NetworkBurstDetection.clustering = clustering;
        NetworkBurstDetection.flag2 = flag2;

        fprintf("\n End of Network Burst detection (%f min) \n", toc(t4)/60);
        shuffleCache('reset');                                              % (revised October 2026) free the memory used by the shuffles
end
end